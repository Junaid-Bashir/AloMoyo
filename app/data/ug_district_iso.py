def lookup_iso(district_name: str) -> str | None:
    """
    Given a district name (e.g. "Kampala District" or "Kampala"),
    return the ISO code (e.g. "UG-102"), or None if unknown.
    """
    key = district_name.upper().replace(" DISTRICT", "")
    return DISTRICT_ISO.get(key)
